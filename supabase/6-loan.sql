--   잔액·금리·매달 갚을 금액을 적어 두면, 계획 탭에서 이자와 다 갚는 달을 계산해요.
-- =====================================================================
create table if not exists gagyebu.loans (
  id         bigint generated by default as identity primary key,
  name       text not null default '마이너스통장',
  balance    integer not null default 0,     -- 지금 마이너스 금액 (양수로 적어요)
  rate       numeric(5, 2),                  -- 연 금리 %
  monthly    integer not null default 0,     -- 매달 갚을 금액
  as_of      date not null default (now() at time zone 'Asia/Seoul')::date,  -- 잔액을 적은 날
  updated_at timestamptz not null default now()
);
alter table gagyebu.loans enable row level security;
revoke all on gagyebu.loans from anon, authenticated;
grant select, insert, update, delete on gagyebu.loans to authenticated;
drop policy if exists "owner all" on gagyebu.loans;
create policy "owner all" on gagyebu.loans for all to authenticated using (gagyebu.is_owner()) with check (gagyebu.is_owner());
