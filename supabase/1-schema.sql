create schema if not exists gagyebu;
grant usage on schema gagyebu to anon, authenticated;

-- 주인 확인 (money 스키마의 주인 목록을 그대로 씀)
create or replace function gagyebu.is_owner()
returns boolean language sql stable security definer set search_path = money as $$
  select money.is_owner();
$$;
revoke all on function gagyebu.is_owner() from public, anon;
grant execute on function gagyebu.is_owner() to authenticated;

-- 1) 카드 ---------------------------------------------------------------
create table if not exists gagyebu.cards (
  id               text primary key,          -- lotte / nh / samsung
  name             text not null,
  sort             int  not null,
  cycle_start      int  not null,             -- 7 → 전월 7일 ~ 이번 달 6일 사용분
  pay_day          int  not null,             -- 결제일
  account          text,                      -- 빠져나가는 통장
  color            text,
  installment_unit int  not null default 100  -- 할부 월 납입액 단위 (원)
);
insert into gagyebu.cards (id, name, sort, cycle_start, pay_day, account, color, installment_unit) values
  ('lotte',   '롯데', 1, 7, 20, '급여 통장', '#7F77DD', 100),
  ('nh',      '농협', 2, 5, 18, '농협 통장', '#1D9E75', 1),
  ('samsung', '삼성', 3, 6, 18, '급여 통장', '#378ADD', 100)
on conflict (id) do update set
  name = excluded.name, sort = excluded.sort, cycle_start = excluded.cycle_start,
  pay_day = excluded.pay_day, account = excluded.account, color = excluded.color,
  installment_unit = excluded.installment_unit;

-- 2) 결제 ---------------------------------------------------------------
create table if not exists gagyebu.payments (
  id               bigint generated by default as identity primary key,
  card_id          text not null references gagyebu.cards(id),
  paid_at          timestamptz not null,       -- 긁은 시각
  amount           integer not null,           -- 긁은 금액 (할인 전). 취소는 음수
  merchant         text,
  memo             text,
  months           integer not null default 1, -- 할부 개월 (1 = 일시불)
  monthly          integer,                    -- 할부 월 납입액 (모르면 비움 → 자동 계산)
  first_bill_month integer,                    -- 할부 첫 청구월 202609 (모르면 비움 → 결제일로 계산)
  source           text not null default 'manual', -- notification / statement / manual
  source_ref       text unique,                -- 중복 방지용 출처 번호
  hidden           boolean not null default false,
  created_at       timestamptz not null default now()
);
create index if not exists payments_paid_at_idx on gagyebu.payments (paid_at);

-- 3) 예산 ---------------------------------------------------------------
create table if not exists gagyebu.budgets (
  bill_month int  not null,                    -- 202612
  card_id    text not null references gagyebu.cards(id),
  amount     integer not null default 0,
  updated_at timestamptz not null default now(),
  primary key (bill_month, card_id)
);

-- 권한: 주인만 ----------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['cards', 'payments', 'budgets'] loop
    execute format('alter table gagyebu.%I enable row level security', t);
    execute format('revoke all on gagyebu.%I from anon, authenticated', t);
    execute format('grant select, insert, update, delete on gagyebu.%I to authenticated', t);
    execute format('drop policy if exists "owner all" on gagyebu.%I', t);
    execute format('create policy "owner all" on gagyebu.%I for all to authenticated using (gagyebu.is_owner()) with check (gagyebu.is_owner())', t);
  end loop;
end $$;

-- 4) 지금 쓰는 알림 수집기와 연결 (새 수집기를 만들 때까지 임시) -------------
--    money.notif_raw 에서 해석된 결제가 들어오면 gagyebu.payments 에도 한 줄 넣어요.
create or replace function gagyebu.from_notif(n money.notif_raw)
returns void language plpgsql security definer set search_path = gagyebu, money, public as $$
begin
  if n.kind not in ('payment', 'cancel') or n.card is null or n.amount is null then return; end if;
  insert into gagyebu.payments (card_id, paid_at, amount, merchant, months, source, source_ref)
  values (
    case n.card when '롯데' then 'lotte' when '삼성' then 'samsung' else 'nh' end,
    coalesce(n.approved_at, n.posted_at, n.created_at),
    case when n.kind = 'cancel' then -abs(n.amount) else abs(n.amount) end,
    n.merchant,
    coalesce(nullif(substring(coalesce(n.installment, '') from '([0-9]+)\s*개월'), '')::int, 1),
    'notification',
    'notif:' || n.id
  )
  on conflict (source_ref) do nothing;
end;
$$;
revoke all on function gagyebu.from_notif(money.notif_raw) from public, anon, authenticated;

create or replace function gagyebu.notif_trigger()
returns trigger language plpgsql security definer set search_path = gagyebu, money, public as $$
begin
  perform gagyebu.from_notif(new);
  return null;
end;
$$;
drop trigger if exists to_gagyebu on money.notif_raw;
create trigger to_gagyebu after insert on money.notif_raw
  for each row execute function gagyebu.notif_trigger();

-- 5) 알림 수집 상태 (화면 맨 위 "마지막 알림 n시간 전") ------------------------
create or replace function gagyebu.collector_status()
returns table (last_any timestamptz, last_payment timestamptz)
language sql stable security definer set search_path = money, gagyebu as $$
  select
    (select max(created_at) from money.notif_raw),
    (select max(created_at) from money.notif_raw where kind in ('payment', 'cancel'))
  where gagyebu.is_owner();
$$;
revoke all on function gagyebu.collector_status() from public, anon;
grant execute on function gagyebu.collector_status() to authenticated;
