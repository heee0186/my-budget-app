-- 테이블
--   gagyebu.cards     카드 3장의 규칙 (이용기간 시작일, 결제일, 통장)
--   gagyebu.payments  결제 한 건 = 한 줄. 할부는 개월 수와 월 납입액으로 관리
--   gagyebu.budgets   청구월 × 카드별 예산 (없는 달은 바로 전 달 값을 씀)
--
-- 청구월: "12월" = 12월 18·20일에 빠져나가는 카드값 (12/17 급여로 갚는 돈)
