-- 예산 설계 (프로젝트 2 · 3-collector.sql 다음에 Run). 여러 번 실행해도 안전해요.
--
--   gagyebu.salaries    청구월별 급여 (202612 = 12/17 급여). 없으면 바로 전 달 금액을 씀
--   gagyebu.plan_items  급여에서 먼저 빼둘 돈: 적금, 고정비, 구독(내 몫), 목돈(나눠 모으기)
--     method: 어디서 나가는지. 계좌·카카오뱅크면 급여에서 빼고,
--             롯데·농협·삼성이면 이미 카드값에 들어가니 빼지 않아요(표시만).
-- =====================================================================

create table if not exists gagyebu.salaries (
  bill_month   int primary key,
  amount       integer not null,
  confirmed_at timestamptz,          -- 급여명세서를 보고 확인한 시각
  updated_at   timestamptz not null default now()
);

create table if not exists gagyebu.plan_items (
  id          bigint generated by default as identity primary key,
  kind        text not null check (kind in ('saving', 'fixed', 'subscription', 'sinking')),
  name        text not null,
  amount      integer not null default 0,  -- 매달 금액 (구독은 내 몫)
  total       integer,                     -- 구독 전체 금액 / 목돈 목표 금액
  pay_day     integer,                     -- 나가는 날
  method      text not null default '계좌', -- 계좌 / 카카오뱅크 / 롯데 / 농협 / 삼성
  start_month integer,                     -- 이 청구월부터 (비우면 처음부터)
  end_month   integer,                     -- 이 청구월까지 (비우면 계속. 목돈은 쓰는 달)
  sort        integer not null default 0,
  created_at  timestamptz not null default now()
);

do $$
declare t text;
begin
  foreach t in array array['salaries', 'plan_items'] loop
    execute format('alter table gagyebu.%I enable row level security', t);
    execute format('revoke all on gagyebu.%I from anon, authenticated', t);
    execute format('grant select, insert, update, delete on gagyebu.%I to authenticated', t);
    execute format('drop policy if exists "owner all" on gagyebu.%I', t);
    execute format('create policy "owner all" on gagyebu.%I for all to authenticated using (gagyebu.is_owner()) with check (gagyebu.is_owner())', t);
  end loop;
end $$;

-- 처음 한 번: 예전 가계부(money.my_budget_table) 마지막 달 설정을 가져와요 --------------
do $$
declare
  c jsonb;
  bm int;
  e jsonb;
  n int := 0;
  num_of text := '[^0-9-]';
begin
  if exists (select 1 from gagyebu.plan_items) or to_regclass('money.my_budget_table') is null then return; end if;
  select id, content into bm, c from money.my_budget_table where content ? 'income' order by id desc limit 1;
  if c is null then return; end if;

  -- 급여
  insert into gagyebu.salaries (bill_month, amount)
  values (bm, nullif(regexp_replace(coalesce(c->>'income', '0'), num_of, '', 'g'), '')::int)
  on conflict (bill_month) do nothing;

  -- 적금, 투자
  if nullif(regexp_replace(coalesce(c->>'savings', ''), num_of, '', 'g'), '')::int > 0 then
    insert into gagyebu.plan_items (kind, name, amount, sort) values ('saving', '적금', regexp_replace(c->>'savings', num_of, '', 'g')::int, 1);
  end if;
  if nullif(regexp_replace(coalesce(c->>'invest', ''), num_of, '', 'g'), '')::int > 0 then
    insert into gagyebu.plan_items (kind, name, amount, sort) values ('saving', '투자', regexp_replace(c->>'invest', num_of, '', 'g')::int, 2);
  end if;

  -- 고정비: 상세 목록이 있으면 항목별로, 없으면 합계 한 줄
  for e in select * from jsonb_array_elements(case when jsonb_typeof(c->'memoFixedList') = 'array' then c->'memoFixedList' else '[]' end) loop
    if coalesce(e->>'name', '') <> '' then
      n := n + 1;
      insert into gagyebu.plan_items (kind, name, amount, pay_day, sort)
      values ('fixed', e->>'name', coalesce(nullif(regexp_replace(coalesce(e->>'amt', ''), num_of, '', 'g'), '')::int, 0),
              nullif(regexp_replace(coalesce(e->>'date', ''), '[^0-9]', '', 'g'), '')::int, n);
    end if;
  end loop;
  if n = 0 and nullif(regexp_replace(coalesce(c->>'fixed', ''), num_of, '', 'g'), '')::int > 0 then
    insert into gagyebu.plan_items (kind, name, amount, sort) values ('fixed', '고정비', regexp_replace(c->>'fixed', num_of, '', 'g')::int, 1);
  end if;
  if nullif(regexp_replace(coalesce(c->>'kye', ''), num_of, '', 'g'), '')::int > 0 then
    insert into gagyebu.plan_items (kind, name, amount, sort) values ('fixed', '계·모임비', regexp_replace(c->>'kye', num_of, '', 'g')::int, 99);
  end if;

  -- 구독: 상세 목록 (결제 수단은 모르니 '계좌'로 두고 나중에 고르기)
  n := 0;
  for e in select * from jsonb_array_elements(case when jsonb_typeof(c->'memoSubscribeList') = 'array' then c->'memoSubscribeList' else '[]' end) loop
    if coalesce(e->>'name', '') <> '' then
      n := n + 1;
      insert into gagyebu.plan_items (kind, name, amount, total, pay_day, sort)
      values ('subscription', e->>'name',
              coalesce(nullif(regexp_replace(coalesce(e->>'amt', ''), num_of, '', 'g'), '')::int, 0),
              coalesce(nullif(regexp_replace(coalesce(e->>'amt', ''), num_of, '', 'g'), '')::int, 0),
              nullif(regexp_replace(coalesce(e->>'date', ''), '[^0-9]', '', 'g'), '')::int, n);
    end if;
  end loop;
  if n = 0 and nullif(regexp_replace(coalesce(c->>'subscribe', ''), num_of, '', 'g'), '')::int > 0 then
    insert into gagyebu.plan_items (kind, name, amount, total, sort) values ('subscription', '구독', regexp_replace(c->>'subscribe', num_of, '', 'g')::int, regexp_replace(c->>'subscribe', num_of, '', 'g')::int, 1);
  end if;
end $$;

-- 수집기 상태에 '마지막 급여명세서 알림' 추가 ---------------------------------
drop function if exists gagyebu.collector_status();
create or replace function gagyebu.collector_status()
returns table (sent_at timestamptz, listener_enabled boolean, listener_alive boolean, battery_ok boolean,
               last_any_notif timestamptz, last_card_notif timestamptz, queue integer,
               last_payment timestamptz, review_count integer, legacy_last timestamptz, last_payslip timestamptz)
language sql stable security definer set search_path = gagyebu, money as $$
  select p.sent_at, p.listener_enabled, p.listener_alive, p.battery_ok,
         p.last_any_notif, p.last_card_notif, p.queue,
         (select max(created_at) from gagyebu.inbox where kind in ('payment', 'cancel')),
         (select count(*)::int from gagyebu.inbox where kind = 'review'),
         (select max(created_at) from money.notif_raw),
         (select max(created_at) from gagyebu.inbox where kind = 'payslip')
  from (select 1) one
  left join lateral (select * from gagyebu.pings order by sent_at desc limit 1) p on true
  where gagyebu.is_owner();
$$;
revoke all on function gagyebu.collector_status() from public, anon;
grant execute on function gagyebu.collector_status() to authenticated;

