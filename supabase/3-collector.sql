-- 새 알림 수집기용 서버 구조  (프로젝트 2 · 1-schema.sql 다음에 Run)
-- 여러 번 실행해도 안전해요.
--
--   gagyebu.inbox   폰이 보낸 카드사 알림 원문. 지우지 않고 쌓여요.
--                   들어오는 순간 카드사별 규칙으로 해석하고, 결제면 payments 에 한 줄 넣어요.
--   gagyebu.pings   폰 수집기의 상태 신호 (30분마다 + 알림 받을 때마다)
--                   알림 내용은 없고 시각·권한 상태만 있어요.
-- =====================================================================

-- 1) 알림 원문 ------------------------------------------------------------
create table if not exists gagyebu.inbox (
  id           bigint generated by default as identity primary key,
  client_id    text unique,              -- 폰이 붙이는 고유번호 (재전송 중복 방지)
  source       text,                     -- toss / nhpay / kakao
  package_name text,
  title        text,
  text         text,
  big_text     text,
  posted_at    timestamptz,
  created_at   timestamptz not null default now(),
  -- 서버 해석 결과
  kind         text,                     -- payment / cancel / payslip / review / ignored
  card_id      text,
  amount       integer,
  merchant     text,
  months       integer,
  approved_at  timestamptz,
  note         text
);
create index if not exists inbox_kind_idx on gagyebu.inbox (kind, created_at);

alter table gagyebu.inbox enable row level security;
revoke all on gagyebu.inbox from anon, authenticated;
grant insert on gagyebu.inbox to anon;
grant select, update, delete on gagyebu.inbox to authenticated;
drop policy if exists "collector insert" on gagyebu.inbox;
drop policy if exists "owner all" on gagyebu.inbox;
create policy "collector insert" on gagyebu.inbox for insert to anon with check (true);
create policy "owner all" on gagyebu.inbox for all to authenticated using (gagyebu.is_owner()) with check (gagyebu.is_owner());

-- 2) 해석기 --------------------------------------------------------------
--   토스(롯데)  제목 "19,000원 결제"   내용 "롯데카드 | 네이버페이(일시불)"
--   카톡(삼성)  제목 "삼성카드"        내용 "삼성0243승인 김*권\n85,668원 일시불\n11/03 11:44 Aliexpress"
--   NH pay     제목 "NH농협카드"      내용 "NH카드1*4*승인\n김*권\n40,000원 일시불\n10/28 17:15\n서울석유 (주) 명성주유소"
--   카톡(택사스) 제목 "택사스(TAXAS)"  내용 "급여명세서가 발급되었습니다"
create or replace function gagyebu.parse_inbox(r gagyebu.inbox)
returns gagyebu.inbox language plpgsql stable as $$
declare
  body   text := coalesce(nullif(r.big_text, ''), nullif(r.text, ''), '');
  posted timestamp := coalesce(r.posted_at, r.created_at, now()) at time zone 'Asia/Seoul';
  m text[]; head text; rest text; yy int; mo int;
begin
  r.kind := null; r.card_id := null; r.amount := null; r.merchant := null;
  r.months := null; r.approved_at := r.posted_at; r.note := null;

  if r.source = 'kakao' and coalesce(r.title, '') ~* '택사스|taxas' then
    r.kind := case when body ~ '급여' then 'payslip' else 'ignored' end;
    return r;
  end if;

  if r.source = 'toss' then
    m := regexp_match(coalesce(r.title, ''), '^\s*([0-9][0-9,]*)\s*원\s*(.*)$');
    if m is null or m[2] !~ '결제|취소' then r.kind := 'ignored'; return r; end if;
    r.amount := replace(m[1], ',', '')::int;
    r.kind := case when m[2] ~ '취소' then 'cancel' else 'payment' end;
    if position('|' in body) > 0 then
      head := btrim(split_part(body, '|', 1));
      rest := btrim(substr(body, position('|' in body) + 1));
    else
      head := body; rest := '';
    end if;
    m := regexp_match(rest, '\(([^()]*)\)\s*$');
    if m is not null and m[1] ~ '일시불|개월|할부' then
      r.months := coalesce(substring(m[1] from '([0-9]+)\s*개월')::int, 1);
      rest := btrim(regexp_replace(rest, '\([^()]*\)\s*$', ''));
    end if;
    r.merchant := nullif(rest, '');
    r.card_id := case when head ~ '롯데' then 'lotte' when head ~ '삼성' then 'samsung' when head ~ 'NH|농협' then 'nh' end;
    if r.card_id is null then r.kind := 'review'; r.note := '토스 결제지만 등록된 카드가 아님: ' || head; end if;
    return r;
  end if;

  if (r.source = 'kakao' and coalesce(r.title, '') ~ '삼성카드') or r.source = 'nhpay' then
    m := regexp_match(body, '(승인취소|취소|승인)');
    if m is null then r.kind := 'ignored'; return r; end if;
    r.kind := case when m[1] ~ '취소' then 'cancel' else 'payment' end;
    r.card_id := case when r.source = 'nhpay' then 'nh' else 'samsung' end;
    m := regexp_match(body, '([0-9]{1,2})/([0-9]{1,2})\s+([0-9]{1,2}):([0-9]{2})[ \t]*\n?[ \t]*([^\n]*)');
    if m is not null then
      mo := m[1]::int;
      yy := extract(year from posted)::int;
      if mo = 12 and extract(month from posted) = 1 then yy := yy - 1; end if;
      begin
        r.approved_at := make_timestamp(yy, mo, m[2]::int, m[3]::int, m[4]::int, 0) at time zone 'Asia/Seoul';
      exception when others then r.approved_at := r.posted_at;
      end;
      r.merchant := nullif(btrim(regexp_replace(m[5], '\s*누적.*$', '')), '');
    end if;
    rest := regexp_replace(body, '(누적|잔액|한도)[^\n]*', '', 'g');
    m := regexp_match(rest, '([0-9][0-9,]*)\s*원\s*(일시불|([0-9]+)\s*개월|할부)?');
    if m is null then
      r.kind := 'review';
      r.note := case when rest ~* '\$|USD|EUR|JPY|CNY|달러|외화' then '외화 결제 (원화 금액 없음)' else '금액을 찾지 못함' end;
      return r;
    end if;
    r.amount := replace(m[1], ',', '')::int;
    r.months := coalesce(m[3]::int, 1);
    return r;
  end if;

  r.kind := 'ignored';
  return r;
end;
$$;

create or replace function gagyebu.inbox_before()
returns trigger language plpgsql security definer set search_path = gagyebu, public as $$
begin
  new := gagyebu.parse_inbox(new);
  return new;
end;
$$;

create or replace function gagyebu.inbox_to_payment(n gagyebu.inbox)
returns void language plpgsql security definer set search_path = gagyebu, public as $$
begin
  if n.kind not in ('payment', 'cancel') or n.card_id is null or n.amount is null then return; end if;
  insert into gagyebu.payments (card_id, paid_at, amount, merchant, months, source, source_ref)
  values (n.card_id, coalesce(n.approved_at, n.posted_at, n.created_at),
          case when n.kind = 'cancel' then -abs(n.amount) else abs(n.amount) end,
          n.merchant, coalesce(n.months, 1), 'notification', 'inbox:' || n.id)
  on conflict (source_ref) do nothing;
end;
$$;

create or replace function gagyebu.inbox_after()
returns trigger language plpgsql security definer set search_path = gagyebu, public as $$
begin
  perform gagyebu.inbox_to_payment(new);
  return null;
end;
$$;

drop trigger if exists inbox_parse on gagyebu.inbox;
create trigger inbox_parse before insert on gagyebu.inbox for each row execute function gagyebu.inbox_before();
drop trigger if exists inbox_payment on gagyebu.inbox;
create trigger inbox_payment after insert on gagyebu.inbox for each row execute function gagyebu.inbox_after();
revoke all on function gagyebu.inbox_before() from public, anon, authenticated;
revoke all on function gagyebu.inbox_after() from public, anon, authenticated;
revoke all on function gagyebu.inbox_to_payment(gagyebu.inbox) from public, anon, authenticated;

-- 규칙을 고친 뒤 다시 해석 (결제로 새로 잡힌 건은 payments 에도 추가):  select gagyebu.reparse_inbox();
create or replace function gagyebu.reparse_inbox()
returns integer language plpgsql security definer set search_path = gagyebu, public as $$
declare r gagyebu.inbox; n integer := 0;
begin
  if not gagyebu.is_owner() and current_user not in ('postgres', 'supabase_admin') then raise exception 'not allowed'; end if;
  for r in select * from gagyebu.inbox loop
    r := gagyebu.parse_inbox(r);
    update gagyebu.inbox set kind = r.kind, card_id = r.card_id, amount = r.amount, merchant = r.merchant,
      months = r.months, approved_at = r.approved_at, note = r.note where id = r.id;
    perform gagyebu.inbox_to_payment(r);
    n := n + 1;
  end loop;
  return n;
end;
$$;
revoke all on function gagyebu.reparse_inbox() from public, anon;

-- 3) 수집기 상태 신호 --------------------------------------------------------
create table if not exists gagyebu.pings (
  device_id        text primary key,
  sent_at          timestamptz not null default now(),
  app_version      text,
  listener_enabled boolean,     -- 알림 접근 권한 켜짐
  listener_alive   boolean,     -- 실제로 연결돼 있음
  battery_ok       boolean,     -- 배터리 제한 없음
  last_any_notif   timestamptz, -- 어떤 앱이든 마지막 알림을 들은 시각 (내용은 안 보냄)
  last_card_notif  timestamptz, -- 토스·NH pay·카톡(삼성카드) 알림을 마지막으로 잡은 시각
  last_sent        timestamptz, -- 서버 전송에 마지막으로 성공한 시각
  queue            integer
);
alter table gagyebu.pings enable row level security;
revoke all on gagyebu.pings from anon, authenticated;
grant select on gagyebu.pings to authenticated;
drop policy if exists "owner read" on gagyebu.pings;
create policy "owner read" on gagyebu.pings for select to authenticated using (gagyebu.is_owner());

create or replace function gagyebu.ping(p jsonb)
returns void language plpgsql security definer set search_path = gagyebu, public as $$
begin
  insert into gagyebu.pings (device_id, sent_at, app_version, listener_enabled, listener_alive, battery_ok,
                             last_any_notif, last_card_notif, last_sent, queue)
  values (left(coalesce(p->>'device_id', 'phone'), 64), now(), left(p->>'app_version', 20),
          (p->>'listener_enabled')::boolean, (p->>'listener_alive')::boolean, (p->>'battery_ok')::boolean,
          (p->>'last_any_notif')::timestamptz, (p->>'last_card_notif')::timestamptz,
          (p->>'last_sent')::timestamptz, (p->>'queue')::int)
  on conflict (device_id) do update set
    sent_at = now(), app_version = excluded.app_version,
    listener_enabled = excluded.listener_enabled, listener_alive = excluded.listener_alive,
    battery_ok = excluded.battery_ok, last_any_notif = excluded.last_any_notif,
    last_card_notif = excluded.last_card_notif, last_sent = excluded.last_sent, queue = excluded.queue;
end;
$$;
revoke all on function gagyebu.ping(jsonb) from public;
grant execute on function gagyebu.ping(jsonb) to anon, authenticated;

-- 4) 가계부 화면용 상태 요약 (1-schema.sql 의 것을 바꿔요) ----------------------
drop function if exists gagyebu.collector_status();
create or replace function gagyebu.collector_status()
returns table (sent_at timestamptz, listener_enabled boolean, listener_alive boolean, battery_ok boolean,
               last_any_notif timestamptz, last_card_notif timestamptz, queue integer,
               last_payment timestamptz, review_count integer, legacy_last timestamptz)
language sql stable security definer set search_path = gagyebu, money as $$
  select p.sent_at, p.listener_enabled, p.listener_alive, p.battery_ok,
         p.last_any_notif, p.last_card_notif, p.queue,
         (select max(created_at) from gagyebu.inbox where kind in ('payment', 'cancel')),
         (select count(*)::int from gagyebu.inbox where kind = 'review'),
         (select max(created_at) from money.notif_raw)
  from (select 1) one
  left join lateral (select * from gagyebu.pings order by sent_at desc limit 1) p on true
  where gagyebu.is_owner();
$$;
revoke all on function gagyebu.collector_status() from public, anon;
grant execute on function gagyebu.collector_status() to authenticated;
