-- 1) 거래 ---------------------------------------------------------------
create table if not exists money.tx (
  id                 bigint generated by default as identity primary key,
  card               text not null,              -- 롯데 / 삼성 / NH / 현금
  amount             integer not null,           -- 원. 취소는 음수
  merchant           text,
  memo               text,
  used_at            timestamptz not null,       -- 결제 시각
  installment_months integer not null default 1, -- 할부 개월 (1 = 일시불)
  source             text not null default 'manual', -- auto / manual / legacy
  raw_id             bigint unique references money.notif_raw(id) on delete set null,
  legacy_key         text unique,
  hidden             boolean not null default false, -- 지운 거래 (원문 추적용으로 남김)
  created_at         timestamptz not null default now()
);
create index if not exists tx_used_at_idx on money.tx (used_at);

alter table money.tx enable row level security;
revoke all on money.tx from anon, authenticated;
grant select, insert, update, delete on money.tx to authenticated;
drop policy if exists "owner all" on money.tx;
create policy "owner all" on money.tx for all to authenticated
  using (money.is_owner()) with check (money.is_owner());

