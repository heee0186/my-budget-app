-- 3) 알림 → 거래 자동 등록 (예전의 sms_inbox 전달을 대체) ------------------
create or replace function money.notif_to_tx(n money.notif_raw)
returns void language plpgsql security definer set search_path = money, public as $$
begin
  if n.kind not in ('payment', 'cancel') or n.card is null or n.amount is null then
    return;
  end if;
  insert into money.tx (card, amount, merchant, used_at, installment_months, source, raw_id)
  values (
    n.card,
    case when n.kind = 'cancel' then -abs(n.amount) else abs(n.amount) end,
    n.merchant,
    coalesce(n.approved_at, n.posted_at, n.created_at),
    coalesce(nullif(substring(coalesce(n.installment, '') from '([0-9]+)\s*개월'), '')::int, 1),
    'auto',
    n.id
  )
  on conflict (raw_id) do nothing;
end;
$$;
revoke all on function money.notif_to_tx(money.notif_raw) from public, anon, authenticated;

create or replace function money.notif_raw_after_insert()
returns trigger language plpgsql security definer set search_path = money, public as $$
begin
  perform money.notif_to_tx(new);
  return null;
end;
$$;

-- 이미 들어와 있는 알림도 거래로 등록
do $$
declare n money.notif_raw;
begin
  for n in select * from money.notif_raw loop
    perform money.notif_to_tx(n);
  end loop;
end $$;

-- 4) 예전 월별 기록의 거래를 복사 (이미 자동 등록된 것과 같으면 건너뜀) -------
create or replace function money.try_date(y int, m int, d int)
returns date language plpgsql immutable as $$
begin
  return make_date(y, m, d);
exception when others then
  return null;
end;
$$;

with src as (
  select b.id as month_id, e.ord, e.t
  from money.my_budget_table b
  cross join lateral jsonb_array_elements(
    case when jsonb_typeof(b.content->'transactions') = 'array' then b.content->'transactions' else '[]'::jsonb end
  ) with ordinality as e(t, ord)
),
parsed as (
  select
    'L' || month_id || ':' || ord as legacy_key,
    t->>'card' as card,
    case when (t->>'amount') ~ '^-?[0-9]+(\.[0-9]+)?$' then round((t->>'amount')::numeric)::int end as amount,
    nullif(btrim(t->>'memo'), '') as memo,
    case
      when (t->>'date') ~ '^\d{4}-\d{1,2}-\d{1,2}' then
        money.try_date((regexp_match(t->>'date', '^(\d{4})-(\d{1,2})-(\d{1,2})'))[1]::int,
                       (regexp_match(t->>'date', '^(\d{4})-(\d{1,2})-(\d{1,2})'))[2]::int,
                       (regexp_match(t->>'date', '^(\d{4})-(\d{1,2})-(\d{1,2})'))[3]::int)
      when (t->>'date') ~ '^\d{1,2}/\d{1,2}$' then
        money.try_date(
          (month_id / 100)::int
            + case when month_id % 100 = 12 and split_part(t->>'date', '/', 1)::int = 1 then 1
                   when month_id % 100 = 1 and split_part(t->>'date', '/', 1)::int = 12 then -1
                   else 0 end,
          split_part(t->>'date', '/', 1)::int,
          split_part(t->>'date', '/', 2)::int)
    end as d
  from src
  where coalesce(t->>'category', '') <> '할부금'
)
insert into money.tx (card, amount, memo, used_at, source, legacy_key)
select p.card, p.amount, p.memo, (p.d + time '12:00') at time zone 'Asia/Seoul', 'legacy', p.legacy_key
from parsed p
where p.card in ('롯데', '삼성', 'NH', '현금')
  and p.amount is not null and p.amount <> 0
  and p.d is not null
  and not exists (
    select 1 from money.tx a
    where a.source = 'auto' and a.card = p.card and a.amount = p.amount
      and (a.used_at at time zone 'Asia/Seoul')::date = p.d
  )
on conflict (legacy_key) do nothing;

