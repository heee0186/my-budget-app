-- [새 개인용 프로젝트]에서 실행
-- 돈 관련 앱(가계부, 결제 알림 수집기, 타오바오 정산) 전용 Supabase 프로젝트를 준비해요.
--
-- 실행 전에: 새 프로젝트의 Authentication → Users → Add user 로
--           가계부에 쓰던 이메일·비밀번호로 계정을 만들어 두세요 (Auto Confirm 체크).
-- 실행 방법: SQL Editor 에 통째로 붙여넣고 [바꿀 곳] 한 군데만 바꾼 뒤 Run.
-- 여러 번 실행해도 안전해요.
--
-- 권한 요약
--   my_budget_table : 주인만 읽고 쓰기
--   sms_inbox       : 수집기 앱(공개 키)은 넣기만, 주인만 읽기·지우기
--   tb_docs         : 주인만 읽고 쓰기 (타오바오 정산도 이제 로그인 필요)
-- =====================================================================

grant usage on schema public to anon, authenticated;

-- 1) 주인 목록과 확인 함수 -------------------------------------------------
create table if not exists public.owners (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.owners enable row level security;
revoke all on public.owners from anon, authenticated;

create or replace function public.is_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.owners where user_id = auth.uid());
$$;
revoke all on function public.is_owner() from public, anon;
grant execute on function public.is_owner() to authenticated;

-- 2) 가계부 ---------------------------------------------------------------
create table if not exists public.my_budget_table (
  id bigint primary key,                 -- 202611 같은 연월
  content jsonb not null default '{}'::jsonb,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);
alter table public.my_budget_table enable row level security;
revoke all on public.my_budget_table from anon, authenticated;
grant select, insert, update, delete on public.my_budget_table to authenticated;
drop policy if exists "owner only" on public.my_budget_table;
create policy "owner only" on public.my_budget_table
  for all to authenticated
  using (public.is_owner()) with check (public.is_owner());

-- 3) 결제 알림 우체통 -------------------------------------------------------
create table if not exists public.sms_inbox (
  id bigint generated by default as identity primary key,
  message text,
  -- 예전 형식 호환용 칸 (지금 수집기는 message 하나만 씀)
  app_name text, package_name text, title text, text text, big_text text, sub_text text,
  created_at timestamptz not null default now()
);
alter table public.sms_inbox enable row level security;
revoke all on public.sms_inbox from anon, authenticated;
-- anon select 권한은 있지만 읽기 정책이 없어 항상 빈 결과
-- (수집기 앱의 "서버 연결 테스트"가 오류 대신 정상으로 나오게)
grant select, insert on public.sms_inbox to anon;
grant select, delete on public.sms_inbox to authenticated;
drop policy if exists "collector insert" on public.sms_inbox;
drop policy if exists "owner read" on public.sms_inbox;
drop policy if exists "owner delete" on public.sms_inbox;
create policy "collector insert" on public.sms_inbox for insert to anon with check (true);
create policy "owner read" on public.sms_inbox for select to authenticated using (public.is_owner());
create policy "owner delete" on public.sms_inbox for delete to authenticated using (public.is_owner());

-- 4) 타오바오 정산 ---------------------------------------------------------
create table if not exists public.tb_docs (
  id text primary key,                   -- 'meta' 또는 'o_주문번호'
  body jsonb not null,
  updated_at timestamptz not null default now()
);
alter table public.tb_docs enable row level security;
revoke all on public.tb_docs from anon, authenticated;
grant select, insert, update, delete on public.tb_docs to authenticated;
drop policy if exists "owner only" on public.tb_docs;
create policy "owner only" on public.tb_docs
  for all to authenticated
  using (public.is_owner()) with check (public.is_owner());

-- 5) 주인 등록  ───────────── [바꿀 곳] 따옴표 안을 내 로그인 이메일로 ─────────────
insert into public.owners (user_id)
select id from auth.users where lower(email) = lower('여기에_내_로그인_이메일')
on conflict do nothing;

-- 6) 확인: owners 가 1 이어야 해요. 0이면 계정을 아직 안 만들었거나 이메일이 달라요.
select
  (select count(*) from public.owners) as owners,
  (select string_agg(u.email, ', ') from public.owners o join auth.users u on u.id = o.user_id) as owner_emails;
