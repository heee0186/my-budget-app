-- 실행 전에: Authentication → Users 에 가계부에 쓸 계정이 있어야 해요.
--           (예절퀘스트 교사용 계정을 그대로 써도 되고, 없으면 Add user → Auto Confirm 체크)
-- 실행 방법: SQL Editor 에 통째로 붙여넣고 [바꿀 곳] 한 군데만 바꾼 뒤 Run.
-- 실행 후에: Project Settings → Data API → Exposed schemas 에 money 를 추가하고 Save.
-- 여러 번 실행해도 안전해요.
--
-- 권한 요약
--   money.my_budget_table : 주인만 읽고 쓰기
--   money.sms_inbox       : 수집기 앱(공개 키)은 넣기만, 주인만 읽기·지우기
--   money.tb_docs         : 주인만 읽고 쓰기
--   예절퀘스트 계정이라도 주인 목록에 없으면 돈 관련 자료는 못 봐요.
