create schema if not exists money;
grant usage on schema money to anon, authenticated;

-- 1) 주인 목록과 확인 함수 -------------------------------------------------
create table if not exists money.owners (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table money.owners enable row level security;
revoke all on money.owners from anon, authenticated;

create or replace function money.is_owner()
returns boolean
language sql
stable
security definer
set search_path = money
as $$
  select exists (select 1 from money.owners where user_id = auth.uid());
$$;
revoke all on function money.is_owner() from public, anon;
grant execute on function money.is_owner() to authenticated;

-- 2) 가계부 ---------------------------------------------------------------
create table if not exists money.my_budget_table (
  id bigint primary key,                 -- 202611 같은 연월
  content jsonb not null default '{}'::jsonb,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);
alter table money.my_budget_table enable row level security;
revoke all on money.my_budget_table from anon, authenticated;
grant select, insert, update, delete on money.my_budget_table to authenticated;
drop policy if exists "owner only" on money.my_budget_table;
create policy "owner only" on money.my_budget_table
  for all to authenticated
  using (money.is_owner()) with check (money.is_owner());

-- 3) 결제 알림 우체통 -------------------------------------------------------
create table if not exists money.sms_inbox (
  id bigint generated by default as identity primary key,
  message text,
  -- 예전 형식 호환용 칸 (지금 수집기는 message 하나만 씀)
  app_name text, package_name text, title text, text text, big_text text, sub_text text,
  created_at timestamptz not null default now()
);
alter table money.sms_inbox enable row level security;
revoke all on money.sms_inbox from anon, authenticated;
-- anon select 권한은 있지만 읽기 정책이 없어 항상 빈 결과
-- (수집기 앱의 "서버 연결 테스트"가 오류 대신 정상으로 나오게)
grant select, insert on money.sms_inbox to anon;
grant select, delete on money.sms_inbox to authenticated;
drop policy if exists "collector insert" on money.sms_inbox;
drop policy if exists "owner read" on money.sms_inbox;
drop policy if exists "owner delete" on money.sms_inbox;
create policy "collector insert" on money.sms_inbox for insert to anon with check (true);
create policy "owner read" on money.sms_inbox for select to authenticated using (money.is_owner());
create policy "owner delete" on money.sms_inbox for delete to authenticated using (money.is_owner());

-- 4) 타오바오 정산 ---------------------------------------------------------
create table if not exists money.tb_docs (
  id text primary key,                   -- 'meta' 또는 'o_주문번호'
  body jsonb not null,
  updated_at timestamptz not null default now()
);
alter table money.tb_docs enable row level security;
revoke all on money.tb_docs from anon, authenticated;
grant select, insert, update, delete on money.tb_docs to authenticated;
drop policy if exists "owner only" on money.tb_docs;
create policy "owner only" on money.tb_docs
  for all to authenticated
  using (money.is_owner()) with check (money.is_owner());

-- 5) 주인 등록  ───────────── [바꿀 곳] 따옴표 안을 내 로그인 이메일로 ─────────────
insert into money.owners (user_id)
select id from auth.users where lower(email) = lower('여기에_내_로그인_이메일')
on conflict do nothing;

-- 6) 확인: owners 가 1 이어야 해요. 0이면 계정을 아직 안 만들었거나 이메일이 달라요.
select
  (select count(*) from money.owners) as owners,
  (select string_agg(u.email, ', ') from money.owners o join auth.users u on u.id = o.user_id) as owner_emails;
